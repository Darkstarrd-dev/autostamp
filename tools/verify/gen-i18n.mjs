#!/usr/bin/env node
// tools/verify/gen-i18n.mjs — regenerate web/static/app-i18n.js from UI_SPEC §4.
//
// The i18n table (key|en|cn) is the single source of truth, so the shipped
// catalogue can never drift from the spec it is validated against
// (AGENTS §10 doc sync). Run: node tools/verify/gen-i18n.mjs
//
// Writes the file only when content changes (keeps git clean / avoids a bare
// commit churn).

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(join(fileURLToPath(import.meta.url)), "..", "..", "..");
const specPath = join(root, "docs", "UI_SPEC.md");
const outPath = join(root, "web", "static", "app-i18n.js");
const spec = readFileSync(specPath, "utf8").replace(/\r\n/g, "\n");
const start = spec.indexOf("\n## 4.");
if (start < 0) throw new Error("UI_SPEC §4 not found");
const afterHeading = spec.slice(start + 1); // "## 4. ..."
const nextIdx = afterHeading.slice(1).search(/^## /m);
if (nextIdx < 0) throw new Error("UI_SPEC: §4 has no following section");
const section = afterHeading.slice(0, nextIdx + 1);
const rows = [...section.matchAll(/^\|([^|\n]+)\|([^|\n]+)\|([^|\n]*)\|\s*$/gm)]
  .map((m) => ({ key: m[1].trim(), en: m[2].trim(), cn: m[3].trim() }))
  .filter((r) => r.key !== "key" && !/^-+$/.test(r.key));
const seen = new Map();
for (const r of rows) {
  if (!r.key || !r.en || !r.cn) throw new Error(`§4 row has empty en/cn: ${JSON.stringify(r)}`);
  if (seen.has(r.key)) throw new Error(`§4 duplicate key: ${r.key}`);
  seen.set(r.key, r);
}
if (seen.size < 120) throw new Error(`§4 looks truncated: only ${seen.size} keys parsed`);

const keys = [...seen.keys()].sort();
const q = (s) => JSON.stringify(s);
const body = [
  "// AutoStamp i18n catalogue (en + cn). GENERATED by tools/verify/gen-i18n.mjs",
  "// from docs/UI_SPEC.md §4 - do not edit by hand; edit the spec table and re-run",
  "// the generator (AGENTS §7 keeps i18n text in one file).",
 `// ${keys.length} keys.`,
 "",
 "(() => {",
 "  \"use strict\";",
 "",
 "  const CATALOG = {",
];
for (const k of keys) {
  const r = seen.get(k);
  body.push(`    ${q(k)}: { en: ${q(r.en)}, cn: ${q(r.cn)} },`);
}
body.push("  };", "", "  window.__autoStampI18n = { CATALOG, keys: Object.keys(CATALOG).sort() };", "})();", "");

const out = body.join("\n");
if (existsSync(outPath) && readFileSync(outPath, "utf8") === out) {
  console.log(`gen-i18n: up to date (${keys.length} keys)`);
} else {
  writeFileSync(outPath, out);
  console.log(`gen-i18n: wrote web/static/app-i18n.js (${keys.length} keys)`);
}
